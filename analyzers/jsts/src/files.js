// The source tree as every command sees it: which files are JavaScript or
// TypeScript sources, which of them are test code or generated, and the
// container (package) each belongs to. Pure functions of paths and contents,
// shared by analyze and test so that both write containers and ids alike.

import { closeSync, openSync, readFileSync, readSync, readdirSync, realpathSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

/** Extensions of the source files analysed. Declaration files (.d.ts) are left out. */
export const SOURCE_EXTENSIONS = [".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs"];

/**
 * Folders never walked: dependencies, build output, caches and coverage reports. Hidden folders (".git",
 * ".next", ".turbo") are skipped too.
 */
export const SKIPPED_FOLDERS = new Set([
  "node_modules",
  "bower_components",
  "jspm_packages",
  "vendor",
  "target",
  "dist",
  "build",
  "out",
  "coverage",
]);

/** Whether a folder named `name` is walked. */
export function walkedFolder(name) {
  return !name.startsWith(".") && !SKIPPED_FOLDERS.has(name);
}

/** Whether `rel` names a source file (by extension; declaration files excluded). */
export function isSourceFile(rel) {
  if (/\.d\.[cm]?ts$/.test(rel) || /\.d\.[^/]*\.ts$/.test(rel)) return false;
  return SOURCE_EXTENSIONS.some((ext) => rel.endsWith(ext));
}

/**
 * The source files of the tree at `root`, relative with "/" separators, sorted. Symbolic links are not followed.
 * `folders` receives every walked folder (relative, "" for the root) when given.
 */
export function sourceFiles(root, { folders = null, deadline = Infinity } = {}) {
  const out = [];
  const walk = (dir, rel) => {
    if (Date.now() > deadline) return;
    folders?.push(rel);
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const entry of entries) {
      const childRel = rel === "" ? entry.name : `${rel}/${entry.name}`;
      if (entry.isDirectory()) {
        if (walkedFolder(entry.name)) walk(join(dir, entry.name), childRel);
      } else if (entry.isFile() && isSourceFile(childRel)) {
        out.push(childRel);
      }
    }
  };
  walk(root, "");
  return out;
}

/** Folder names that hold test code by convention. */
const TEST_FOLDERS = new Set(["__tests__", "__mocks__", "__fixtures__", "test", "tests", "spec", "e2e"]);

/**
 * Whether `rel` is test code by the ecosystem's conventions: *.test.* and *.spec.* files (Jest, Vitest, Mocha,
 * node --test), test-*.js / *-test.js / *_test.js / test.js (node --test defaults), and anything under a
 * __tests__, __mocks__, test, tests, spec or e2e folder.
 */
export function isTestFile(rel) {
  const parts = rel.split("/");
  const base = parts.at(-1);
  if (/\.(test|spec)\.[cm]?[jt]sx?$/.test(base)) return true;
  if (/^(test|test-.+|.+[-_]test)\.[cm]?[jt]sx?$/.test(base)) return true;
  return parts.slice(0, -1).some((part) => TEST_FOLDERS.has(part));
}

/** Whether `rel` is the file name of a generated or bundled file, whatever its contents. */
function generatedName(rel) {
  return /\.min\.[cm]?js$/.test(rel) || /\.(generated|gen)\.[cm]?[jt]sx?$/.test(rel) || rel.split("/").includes("__generated__");
}

const GENERATED_MARKER = /@generated\b|\bcode generated\b|do not edit|auto-?generated|<auto-generated/i;

/**
 * Whether a file is generated: by its name (*.min.js, *.generated.ts, __generated__/), by a marker in the
 * comments that open it ("@generated", "Code generated ... DO NOT EDIT", "auto-generated"), or because it is
 * minified (no line break in its first 2 KiB).
 */
export function isGenerated(rel, head) {
  if (generatedName(rel)) return true;
  if (head.length >= 2048 && !head.slice(0, 2048).includes("\n")) return true;
  return GENERATED_MARKER.test(leadingComments(head));
}

/** The comments (and a shebang) before the first statement of `text`. */
export function leadingComments(text) {
  let i = 0;
  let out = "";
  if (text.startsWith("#!")) {
    const end = text.indexOf("\n");
    i = end < 0 ? text.length : end + 1;
  }
  for (;;) {
    while (i < text.length && /\s/.test(text[i])) i++;
    if (text.startsWith("//", i)) {
      const end = text.indexOf("\n", i);
      const stop = end < 0 ? text.length : end;
      out += `${text.slice(i, stop)}\n`;
      i = stop;
    } else if (text.startsWith("/*", i)) {
      const end = text.indexOf("*/", i + 2);
      const stop = end < 0 ? text.length : end + 2;
      out += `${text.slice(i, stop)}\n`;
      i = stop;
    } else if (/^["']use strict["'];?/.test(text.slice(i, i + 13))) {
      i += text.slice(i).match(/^["']use strict["'];?/)[0].length;
    } else {
      return out;
    }
  }
}

/** The first `size` bytes of a file, as text ("" when it cannot be read). */
export function readHead(file, size = 4096) {
  let fd;
  try {
    fd = openSync(file, "r");
    const buffer = Buffer.alloc(size);
    const read = readSync(fd, buffer, 0, size, 0);
    return buffer.subarray(0, read).toString("utf8");
  } catch {
    return "";
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

/** The relative path of `rel` without its extension: the module path functions ids start with. */
export function modulePath(rel) {
  return rel.replace(/\.[cm]?[jt]sx?$/, "");
}

/**
 * The container of a file, as analyze writes it and test lists packages: the folder of the file relative to the
 * tree ("src/routes"), or for a file at the root the package name of the root package.json, else ".".
 */
export function containerOf(rel, rootName = ".") {
  const slash = rel.lastIndexOf("/");
  return slash < 0 ? rootName : rel.slice(0, slash);
}

/** The name of the package at the root of the tree, the container of root files ("." without one). */
export function rootContainerName(root) {
  const pkg = readJson(join(root, "package.json"));
  return typeof pkg?.name === "string" && pkg.name.trim() !== "" ? pkg.name.trim() : ".";
}

/** The parsed JSON file at `file`, or null when it is missing or invalid. Comments and trailing commas are allowed. */
export function readJson(file) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    return null;
  }
  try {
    return JSON.parse(text);
  } catch {
    try {
      return JSON.parse(stripJsonComments(text));
    } catch {
      return null;
    }
  }
}

/** `text` without // and /* comments and without trailing commas, strings left alone (for tsconfig-like files). */
export function stripJsonComments(text) {
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j;
    } else if (c === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && text[i + 1] === "*") {
      const end = text.indexOf("*/", i + 2);
      i = end < 0 ? text.length : end + 1;
    } else {
      out += c;
    }
  }
  return out.replace(/,(\s*[}\]])/g, "$1");
}

/**
 * Turns absolute paths printed by tools into paths relative to the tree. The tree may be reached through a
 * symbolic link (/var and /private/var on macOS), so both forms of the root are tried.
 */
export class Tree {
  constructor(dir) {
    this.root = resolve(dir);
    this.roots = [this.root];
    try {
      const real = realpathSync(this.root);
      if (real !== this.root) this.roots.push(real);
    } catch {
      // The root itself was checked by the caller.
    }
  }

  /** `file` relative to the tree with "/", or null when it lies outside (or is not absolute). */
  rel(file) {
    if (typeof file !== "string" || file === "") return null;
    if (file.startsWith("file://")) {
      try {
        file = decodeURIComponent(new URL(file).pathname);
      } catch {
        return null;
      }
    }
    if (!file.startsWith("/")) return null;
    for (const root of this.roots) {
      const rel = relative(root, file);
      if (rel !== "" && !rel.startsWith("..") && !rel.startsWith(sep)) return rel.split(sep).join("/");
    }
    return null;
  }

  abs(rel) {
    return join(this.root, rel);
  }
}
