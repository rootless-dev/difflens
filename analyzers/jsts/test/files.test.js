import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { Tree, containerOf, isGenerated, isSourceFile, isTestFile, leadingComments, modulePath, sourceFiles, stripJsonComments } from "../src/files.js";
import { fixture } from "./helpers.js";

describe("files", () => {
  it("recognises test files by the ecosystem's conventions", () => {
    for (const rel of ["src/a.test.ts", "a.spec.jsx", "src/__tests__/x.js", "test/helpers.js", "tests/x.ts", "lib/test-x.mjs", "x_test.cjs", "test.js"]) {
      assert.ok(isTestFile(rel), rel);
    }
    for (const rel of ["src/a.ts", "src/testing.ts", "contest.js", "src/latest/x.js"]) assert.ok(!isTestFile(rel), rel);
  });

  it("takes source files and leaves declaration files out", () => {
    assert.ok(isSourceFile("a.cts") && isSourceFile("a.jsx") && isSourceFile("b.mjs"));
    assert.ok(!isSourceFile("a.d.ts") && !isSourceFile("a.d.mts") && !isSourceFile("a.json") && !isSourceFile("styles.d.css.ts"));
  });

  it("flags generated files by header, name and minification", () => {
    assert.ok(isGenerated("a.ts", "// Code generated by x. DO NOT EDIT.\nexport {}"));
    assert.ok(isGenerated("a.ts", "/* eslint-disable */\n/**\n * @generated\n */\nexport {}"));
    assert.ok(isGenerated("vendor.min.js", "x"));
    assert.ok(isGenerated("src/__generated__/a.ts", ""));
    assert.ok(isGenerated("a.js", "x".repeat(3000)));
    assert.ok(!isGenerated("a.ts", "export const note = 'do not edit this by hand';\n"));
    assert.ok(!isGenerated("a.ts", "// A helper.\nexport function f() {}\n// DO NOT EDIT below\n"));
  });

  it("reads the comments that open a file, after a shebang and use strict", () => {
    assert.equal(leadingComments('#!/usr/bin/env node\n"use strict";\n// one\n/* two */\ncode()'), "// one\n/* two */\n");
  });

  it("names modules and containers like analyze", () => {
    assert.equal(modulePath("src/a.test.ts"), "src/a.test");
    assert.equal(containerOf("src/routes/a.ts", "pkg"), "src/routes");
    assert.equal(containerOf("index.js", "pkg"), "pkg");
  });

  it("walks the tree without dependencies, build output and hidden folders", () => {
    const files = sourceFiles(fixture("jsproj"));
    assert.ok(files.includes("lib/greet.js") && files.includes("src/App.jsx") && files.includes("lib/legacy.cjs"));
    assert.ok(!files.some((f) => f.startsWith("dist/") || f.includes("node_modules")));
  });

  it("reads JSON with comments and trailing commas", () => {
    assert.deepEqual(JSON.parse(stripJsonComments('{ // c\n "a": "//not", /* x */ "b": [1,],\n}')), { a: "//not", b: [1] });
  });

  it("places absolute and file:// paths in the tree", () => {
    const tree = new Tree("/tmp/x");
    assert.equal(tree.rel("/tmp/x/a/b.ts"), "a/b.ts");
    assert.equal(tree.rel("file:///tmp/x/a%20b.ts"), "a b.ts");
    assert.equal(tree.rel("/tmp/y/a.ts"), null);
    assert.equal(tree.rel("a.ts"), null);
  });
});
