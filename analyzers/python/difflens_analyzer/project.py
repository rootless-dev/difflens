"""The Python files of a source tree and the module each one is.

Module names are what `import` would use, so that calls resolve through
imports and every command (analyze, test) names a file's container the same
way:

- Source roots are the tree itself, every folder holding a pyproject.toml,
  setup.cfg or setup.py, the `src/` folder next to any of them, and the
  folders their configuration names (setuptools `package-dir` and
  `packages.find.where`, Poetry `packages[].from`).
- A file's module is its path below the deepest root that contains it, with
  `/` as `.`, `.py` dropped and `pkg/__init__.py` named `pkg`. Folders
  without `__init__.py` are namespace packages, as Python treats them.
- When two files would get the same name (two projects of a monorepo both
  with an `app` package), both are named from the tree root instead.

Folders that are not source are skipped: version control, caches, virtual
environments (any folder with a `pyvenv.cfg`), `node_modules`, `.tox`,
`.nox`, `*.egg-info`, and `build`/`dist` unless they are packages.
"""

from __future__ import annotations

import configparser
import os
import re
from dataclasses import dataclass, field
from typing import Any

from difflens_analyzer import toml

SKIP_DIRS = {
    ".git", ".hg", ".svn", "__pycache__", "node_modules", ".tox", ".nox", ".eggs",
    "site-packages", ".mypy_cache", ".ruff_cache", ".pytest_cache", ".venv", "venv",
    ".direnv", ".idea", ".vscode", "htmlcov", ".hypothesis", ".cache", "__pypackages__",
}
# Skipped unless they are packages (hold an __init__.py).
ARTIFACT_DIRS = {"build", "dist", "env", ".env"}
PROJECT_FILES = ("pyproject.toml", "setup.cfg", "setup.py")
TEST_DIRS = {"tests", "test"}

_GENERATED = re.compile(
    r"\b(code generated|generated by|auto-?generated|do not edit|@generated)\b", re.IGNORECASE
)


@dataclass
class SourceFile:
    rel: str  # relative to the tree, "/" separators
    path: str  # absolute
    module: str  # dotted module name
    is_package: bool  # an __init__.py
    test: bool

    @property
    def package(self) -> str:
        """The package relative imports of this file start from."""
        if self.is_package:
            return self.module
        return self.module.rpartition(".")[0]


@dataclass
class Project:
    root: str  # absolute, as given
    real_root: str  # symlinks resolved
    files: list[SourceFile] = field(default_factory=list)
    by_module: dict[str, SourceFile] = field(default_factory=dict)
    by_rel: dict[str, SourceFile] = field(default_factory=dict)
    roots: list[str] = field(default_factory=list)  # source roots, relative ("" is the tree)
    projects: list[str] = field(default_factory=list)  # folders with a project file, relative
    pyprojects: dict[str, dict[str, Any]] = field(default_factory=dict)  # by folder
    prefixes: set[str] = field(default_factory=set)  # packages, namespace ones included

    def rel(self, path: str) -> str | None:
        """path relative to the tree with "/", or None when it lies outside."""
        if not path:
            return None
        if not os.path.isabs(path):
            path = os.path.join(self.root, path)
        for root in (self.root, self.real_root):
            rel = os.path.relpath(os.path.normpath(path), root)
            if not rel.startswith("..") and not os.path.isabs(rel):
                return rel.replace(os.sep, "/")
        real = os.path.realpath(path)
        rel = os.path.relpath(real, self.real_root)
        if not rel.startswith("..") and not os.path.isabs(rel):
            return rel.replace(os.sep, "/")
        return None

    def file_at(self, path: str) -> SourceFile | None:
        rel = self.rel(path)
        return self.by_rel.get(rel) if rel is not None else None

    def is_tree_module(self, name: str) -> bool:
        """A module or namespace package of the tree."""
        return name in self.by_module or name in self.prefixes

    def pyproject(self, folder: str = "") -> dict[str, Any]:
        return self.pyprojects.get(folder, {})

    def source_root(self, rel: str) -> str:
        """The source root a file's module name starts from."""
        return _root_of(rel, self.roots)

    def project_folder(self, rel: str) -> str:
        """The innermost folder with a project file that contains rel, "" for the tree."""
        best = ""
        for folder in self.projects:
            if folder and rel.startswith(folder + "/") and len(folder) > len(best):
                best = folder
        return best


def is_test_path(rel: str) -> bool:
    """pytest's and unittest's conventions: test_*.py, *_test.py, conftest.py, tests/ folders."""
    parts = rel.split("/")
    name = parts[-1]
    if name == "conftest.py" or name.startswith("test_") or name.endswith("_test.py"):
        return True
    return any(part in TEST_DIRS for part in parts[:-1])


def is_generated(source: bytes, rel: str = "") -> bool:
    """A generated-file header among the first comment lines, or a protobuf module name."""
    name = rel.rsplit("/", 1)[-1]
    if name.endswith(("_pb2.py", "_pb2_grpc.py")):
        return True
    for index, raw in enumerate(source.splitlines()[:15]):
        line = raw.strip()
        if not line:
            continue
        if not line.startswith(b"#"):
            # A generator's docstring header counts too, on its first lines.
            if index < 3 and line[:3] in (b'"""', b"'''") and _GENERATED.search(line.decode("utf-8", "replace")):
                return True
            break
        if _GENERATED.search(line.decode("utf-8", "replace")):
            return True
    return False


def discover(root: str, deadline: float | None = None) -> Project:
    """Every Python file of the tree at root, with its module name."""
    import time

    root = os.path.abspath(root)
    project = Project(root=root, real_root=os.path.realpath(root))
    rels: list[str] = []
    for folder, dirs, names in os.walk(root):
        if deadline is not None and time.monotonic() > deadline:
            break
        rel_folder = os.path.relpath(folder, root).replace(os.sep, "/")
        rel_folder = "" if rel_folder == "." else rel_folder
        kept = []
        for name in sorted(dirs):
            full = os.path.join(folder, name)
            if os.path.islink(full) or name in SKIP_DIRS or name.endswith(".egg-info"):
                continue
            if os.path.exists(os.path.join(full, "pyvenv.cfg")):
                continue
            if name in ARTIFACT_DIRS and not os.path.exists(os.path.join(full, "__init__.py")):
                continue
            kept.append(name)
        dirs[:] = kept
        if any(name in names for name in PROJECT_FILES):
            project.projects.append(rel_folder)
        for name in sorted(names):
            if name.endswith(".py"):
                rels.append(f"{rel_folder}/{name}" if rel_folder else name)
    for folder in project.projects:
        path = os.path.join(root, folder, "pyproject.toml")
        if os.path.isfile(path):
            project.pyprojects[folder] = toml.load_file(path)
    project.roots = _source_roots(project)
    _name_modules(project, rels)
    return project


def _join(folder: str, sub: str) -> str:
    sub = sub.strip().strip("/").replace("\\", "/")
    if sub in ("", "."):
        return folder
    return f"{folder}/{sub}" if folder else sub


def _source_roots(project: Project) -> list[str]:
    roots = {""}
    for folder in project.projects:
        roots.add(folder)
        if os.path.isdir(os.path.join(project.root, folder, "src")):
            roots.add(_join(folder, "src"))
        for sub in _configured_roots(project, folder):
            if os.path.isdir(os.path.join(project.root, folder, sub)):
                roots.add(_join(folder, sub))
    if os.path.isdir(os.path.join(project.root, "src")):
        roots.add("src")
    return sorted(roots, key=lambda r: (r.count("/") + (1 if r else 0), r))


def _configured_roots(project: Project, folder: str) -> list[str]:
    found: list[str] = []
    data = project.pyproject(folder)
    setuptools = data.get("tool", {}).get("setuptools", {})
    if isinstance(setuptools, dict):
        package_dir = setuptools.get("package-dir")
        if isinstance(package_dir, dict) and isinstance(package_dir.get(""), str):
            found.append(package_dir[""])
        packages = setuptools.get("packages")
        if isinstance(packages, dict):
            where = packages.get("find", {}).get("where") if isinstance(packages.get("find"), dict) else None
            if isinstance(where, list):
                found.extend(w for w in where if isinstance(w, str))
    poetry = data.get("tool", {}).get("poetry", {})
    if isinstance(poetry, dict) and isinstance(poetry.get("packages"), list):
        for item in poetry["packages"]:
            if isinstance(item, dict) and isinstance(item.get("from"), str):
                found.append(item["from"])
    setup_cfg = os.path.join(project.root, folder, "setup.cfg")
    if os.path.isfile(setup_cfg):
        parser = configparser.ConfigParser()
        try:
            parser.read(setup_cfg, encoding="utf-8")
            package_dir = parser.get("options", "package_dir", fallback="")
            for line in package_dir.splitlines():
                key, _, value = line.partition("=")
                if key.strip() == "" and value.strip():
                    found.append(value.strip())
            where = parser.get("options.packages.find", "where", fallback="")
            found.extend(w.strip() for w in where.splitlines() if w.strip())
        except (configparser.Error, UnicodeDecodeError):
            pass
    return found


def _module_name(rel: str, root: str) -> tuple[str, bool]:
    inner = rel[len(root) + 1 :] if root else rel
    parts = inner[: -len(".py")].split("/")
    is_package = parts[-1] == "__init__"
    if is_package:
        parts = parts[:-1]
    return ".".join(parts), is_package


def _root_of(rel: str, roots: list[str]) -> str:
    best = ""
    for root in roots:
        if root and (rel.startswith(root + "/")) and len(root) > len(best):
            best = root
    return best


def _name_modules(project: Project, rels: list[str]) -> None:
    named: list[tuple[str, str, bool]] = []
    for rel in rels:
        module, is_package = _module_name(rel, _root_of(rel, project.roots))
        if not module:
            # An __init__.py at a source root: the folder is the package.
            folder = os.path.dirname(os.path.join(project.root, rel))
            module = os.path.basename(folder) or "__init__"
        named.append((rel, module, is_package))
    counts: dict[str, int] = {}
    for _, module, _ in named:
        counts[module] = counts.get(module, 0) + 1
    for rel, module, is_package in named:
        if counts[module] > 1:
            module, is_package = _module_name(rel, "")
            module = module or "__init__"
        if module in project.by_module:
            module = f"{module}({rel})"
        source = SourceFile(
            rel=rel,
            path=os.path.join(project.root, rel),
            module=module,
            is_package=is_package,
            test=is_test_path(rel),
        )
        project.files.append(source)
        project.by_module[module] = source
        project.by_rel[rel] = source
        parts = module.split(".")
        for end in range(1, len(parts)):
            project.prefixes.add(".".join(parts[:end]))
